"""
Public webhook endpoint for remote agent triggers (Tier 4).

External systems (GitHub Actions, Slack, Linear, cron servers, anything
that can POST JSON) hit `/api/v1/triggers/<token>` to wake the agent.
No header auth — the token in the URL IS the secret. Each token is 32
random URL-safe bytes (~43 chars), generated by RemoteTriggerService
and only visible once at creation time.

Body is accepted as either JSON or text/plain; size is capped at 256 KB
to keep the agent context budget sane. We accept ALL HTTP methods on the
trigger path because some webhook senders (GitHub, etc.) use POST while
others use PUT or even GET with query params — but the canonical use is
POST + JSON.
"""

import structlog
from fastapi import APIRouter, HTTPException, Request

from app.services.remote_trigger import (
    remote_trigger_service,
    _MAX_PAYLOAD_BYTES,
)

logger = structlog.get_logger()

router = APIRouter(prefix="/api/v1/triggers", tags=["triggers"])


@router.post("/{token}")
async def fire_remote_trigger(token: str, request: Request):
    """Receive a webhook POST and inject a turn into the agent conversation.

    Returns 200 with {accepted, delivered, trigger_id} for tracking. Even
    when delivery fails (OC session gone, conversation deleted), we return
    200 + delivered=false rather than a 4xx — webhook senders that retry
    on errors would otherwise spam the trigger.
    """
    body_bytes = await request.body()
    if len(body_bytes) > _MAX_PAYLOAD_BYTES:
        raise HTTPException(
            status_code=413,
            detail=f"payload too large ({len(body_bytes)} bytes, max {_MAX_PAYLOAD_BYTES})",
        )
    try:
        body_text = body_bytes.decode("utf-8", errors="replace")
    except Exception:
        body_text = ""

    result = await remote_trigger_service.fire(token, body_text)
    if not result.get("accepted"):
        # Unknown / inactive token — return 404 so the caller knows to stop
        # retrying. Use a generic message so we don't leak which tokens
        # exist (timing-safe lookup would be better long-term).
        raise HTTPException(status_code=404, detail="trigger not found")
    return result
